/* Генерирует уникальные описания и вместимость (meta.users) для карточек js/data.js.
 * Источники фактов: ПК «Мультпласт» (multplast.ru: вместимость моделей, особенности корпуса,
 * комплектации S/PR) и параметры самого каталога (объём, габариты, производительность).
 * Запуск: node tools/enrich.js  (затем node tools/build.js) */
const fs = require("fs");
const path = require("path");
const file = path.join(__dirname, "..", "js", "data.js");
const sb = {};
new Function("window", fs.readFileSync(file, "utf8"))(sb);
const P = sb.DELTA_PRODUCTS;
const nf = (n) => new Intl.NumberFormat("ru-RU").format(n).replace(/\u00a0/g, " ");
const hash = (s) => [...s].reduce((a, c) => (a * 31 + c.charCodeAt(0)) >>> 0, 7);
const pick = (arr, id, off = 0) => arr[(hash(id) + off) % arr.length];
const up = (n) => `до ${n} ${n === 1 ? "человека" : "человек"}`;

/* вместимость по таблице производителя */
const PROFI = { "0.7": 1, "1.2": 2, "2.0": 4, "2.5": 5, "3.0": 6, "4.0": 8, "5.5": 12, "6.5": 15, "8.5": 20 };
const PROFI_M = { 15: 30, 20: 40, 25: 50, 30: 60, 35: 70, 40: 80, 45: 90, 50: 100 };
P.forEach((p) => {
  p.meta = p.meta || {};
  if (p.collection === "Термит Профи") {
    p.meta.users = PROFI[p.meta.size];
    p.meta.liters = Math.round(Number(p.meta.size) * 1000);
  }
  if (p.collection === "Термит Профи М") {
    const n = Number(p.id.match(/(\d+)$/)[1]);
    p.meta.model = `М${n}`;
    p.meta.users = PROFI_M[n];
  }
  if (p.collection === "Модуль ST") p.meta.users = Number(p.meta.model.replace(/\D/g, ""));
});

const line = (p) => P.filter((x) => x.collection === p.collection && x.category === p.category && x.category !== "components");
const sorted = (p, key) => line(p).filter((x) => x.meta && x.meta[key]).sort((a, b) => a.meta[key] - b.meta[key]);
function neighbours(p, key, unit) {
  const s = sorted(p, key).filter((x) => !x.meta.compact === !p.meta.compact && !x.meta.long === !p.meta.long);
  const i = s.findIndex((x) => x.id === p.id);
  const prev = s[i - 1], next = s[i + 1];
  const byUsers = key === "users";
  const f = (x) => (byUsers ? `${x.name} (${up(x.meta.users)})` : x.name);
  if (prev && next) return byUsers ? `Если нагрузка выше — смотрите ${f(next)}, если ниже — ${f(prev)}.` : `Нужен больший объём — смотрите ${f(next)}, меньший — ${f(prev)}.`;
  if (next) return byUsers ? `Это самая компактная модель линейки; следующий типоразмер — ${f(next)}.` : `Это самый малый объём в линейке; следующий размер — ${f(next)}.`;
  if (prev) return byUsers ? `Это самая производительная модель линейки; ступенью ниже — ${f(prev)}.` : `Это самый большой объём в линейке; ступенью ниже — ${f(prev)}.`;
  return "";
}

