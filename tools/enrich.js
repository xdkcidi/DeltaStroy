function route(p) {
  if (p.category === "components") return gen.component;
  const c = p.collection;
  if (c === "Термит Профи") return gen.profi;
  if (c === "Термит Профи М") return gen.profiM;
  if (c === "Термит Трансформер") return gen.transformer;
  if (c === "Ergobox") return gen.ergobox;
  if (c === "Пеликан") return gen.pelican;
  if (c === "Модуль ST") return gen.st;
  if (c === "Модуль М") return null;
  if (p.category === "storage") return tank("storage");
  if (c === "ДПВ — питьевая вода") return tank("dpv");
  if (c === "Техническая вода КР") return tank("kr");
  if (c === "Ёмкости КАС") return tank("kas");
  if (p.category === "fuel") return tank("diesel");
  if (p.category === "modular") return tank("modular");
  if (p.category === "water") return tank("water");
  if (p.category === "fire") return tank("fire");
  if (p.category === "storm") return tank("sand");
  if (p.category === "grease") return gen.grease;
  if (p.category === "oil") return gen.oil;
  if (p.category === "sorption") return gen.sorption;
  if (p.category === "rain") return gen.rain;
  if (p.category === "kns") return gen.kns;
  if (p.category === "wells") return gen.well;
  if (p.category === "kesson") return gen.kesson;
  return null;
}

